export const porSlug = new Map(pesquisadoras.map((p) => [p.slug, p]));

export function vizinhas(slug: string) {
  const i = pesquisadoras.findIndex((p) => p.slug === slug);
  const n = pesquisadoras.length;
  return {
    indice: i + 1,
    total: n,
    anterior: pesquisadoras[(i - 1 + n) % n],
    proxima: pesquisadoras[(i + 1) % n],
  };
}

export function relacionadas(p: Pesquisadora, limite = 4): Pesquisadora[] {
  const escolhidas = new Map<string, Pesquisadora>();
  const add = (x?: Pesquisadora) => {
    if (x && x.slug !== p.slug && !escolhidas.has(x.slug) && escolhidas.size < limite) escolhidas.set(x.slug, x);
  };
  (p.conexoes ?? []).forEach((s) => add(porSlug.get(s)));
  pesquisadoras.filter((x) => x.area === p.area && x.regiao === p.regiao).forEach(add);
  pesquisadoras.filter((x) => p.uf && x.uf === p.uf).forEach(add);
  pesquisadoras.filter((x) => x.area === p.area).forEach(add);
  return [...escolhidas.values()];
}

export function contarPorUF(): Partial<Record<UF, number>> {
  const r: Partial<Record<UF, number>> = {};
  for (const p of pesquisadoras) if (p.uf) r[p.uf] = (r[p.uf] ?? 0) + 1;
  return r;
}

export function rotuloLocal(p: Pesquisadora): string {
  return p.uf ? `${UFS[p.uf].nome} (${p.uf})` : p.estadoOuPais;
}

export function iniciais(p: Pesquisadora): string {
  const partes = p.nomeCurto
    .replace(/^(As|Os|Programadoras|do)\s+/gi, '')
    .split(/\s+/)
    .filter((w) => !/^(de|da|do|dos|das|e)$/i.test(w));
  if (p.slug === 'programadoras-do-eniac') return 'EN';
  return ((partes[0]?.[0] ?? '') + (partes[partes.length - 1]?.[0] ?? '')).toUpperCase();
}

export function miniatura(p: Pesquisadora): string | null {
  return p.foto ? p.foto.replace('/pesquisadoras/', '/pesquisadoras/min/') : null;
}

